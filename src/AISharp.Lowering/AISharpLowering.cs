using AISharp.Compiler;
using System.Text;
using System.Text.RegularExpressions;

namespace AISharp.Lowering;

// ─── Lowering result ──────────────────────────────────────────────────────────

/// <summary>
/// Result of lowering a <see cref="MirDocument"/> to generated C# source.
/// </summary>
public sealed record LoweringResult(
    string GeneratedCSharpSource,
    IReadOnlyDictionary<string, SourceLocation> SourceMap,
    DebugSourceMap? DebugMap = null);

// ─── AISharp lowering API ─────────────────────────────────────────────────────

/// <summary>
/// Lowers a typed <see cref="MirDocument"/> (the <c>ITypedMirArtifact</c> boundary) to
/// generated C# source text. The generated C# is designed so that Roslyn syntax-tree
/// lowering can be layered on top later without breaking existing API shapes.
/// </summary>
public static partial class AISharpLowering
{
    private sealed record LoweringContext(
        IReadOnlySet<string> RecordTypes,
        IReadOnlyDictionary<string, string> UnionCaseOwners);

    /// <summary>
    /// Lower the given <paramref name="document"/> to a <see cref="LoweringResult"/>
    /// containing the generated C# source and a source map.
    /// </summary>
    public static LoweringResult Lower(MirDocument document)
    {
        if (document.ScalarValidationFailed)
            throw new InvalidOperationException("Scalar validation failed; lowering is prohibited.");
        var sb = new StringBuilder();
        var sourceMap = new Dictionary<string, SourceLocation>(StringComparer.Ordinal);
        var debugEntries = new List<DebugMapEntry>();

        var rawNs = document.Module ?? document.Intent ?? "AISharp.Generated";
        var ns = SanitizeNamespace(rawNs);

        sb.AppendLine("// Generated by AISharp compiler");
        sb.AppendLine("using System.Threading.Tasks;");
        sb.AppendLine($"namespace {ns}");
        sb.AppendLine("{");
        AppendContractRuntimeSupport(sb);
        sb.AppendLine();
        sb.AppendLine("    public static class AISharpModule");
        sb.AppendLine("    {");

        var context = BuildContext(document);

        LowerTypes(sb, document);

        foreach (var fn in document.Functions)
        {
            sourceMap[$"fn:{fn.Name}"] = fn.Location;

            var genStart = CountNewlines(sb);
            var scalar = document.ScalarFunctions.FirstOrDefault(f => f.Name == fn.Name);
            if (scalar is not null) LowerScalarFunction(sb, scalar);
            else LowerFunction(sb, fn, context);
            var genEnd = CountNewlines(sb) - 1;

            var aiLine = Math.Max(0, fn.Location.Line - 1);
            debugEntries.Add(new DebugMapEntry(
                $"fn:{fn.Name}",
                new DebugSpan(aiLine, 0, aiLine + 1, 0),
                new DebugSpan(genStart, 0, genEnd, 0)));
        }

        sb.AppendLine("    }");

        AppendEffectRuntimeSupport(sb);
        foreach (var actor in document.Actors)
        {
            foreach (var handler in actor.Handlers)
            {
                sourceMap[$"fn:{handler.Name}"] = handler.Location;

                var genStart = CountNewlines(sb);
                // Actor handlers are lowered as part of LowerActor below.
                var aiLine = Math.Max(0, handler.Location.Line - 1);
                debugEntries.Add(new DebugMapEntry(
                    $"fn:{handler.Name}",
                    new DebugSpan(aiLine, 0, aiLine + 1, 0),
                    new DebugSpan(genStart, 0, genStart + 1, 0)));
            }
            LowerActor(sb, actor, context);
        }

        sb.AppendLine("}");

        return new LoweringResult(sb.ToString(), sourceMap, new DebugSourceMap(debugEntries));
    }

    private static int CountNewlines(StringBuilder sb)
    {
        var count = 0;
        for (var i = 0; i < sb.Length; i++)
            if (sb[i] == '\n') count++;
        return count;
    }

    private static LoweringContext BuildContext(MirDocument document)
    {
        var records = document.Types
            .Where(t => t.Kind == TypeKind.Record)
            .Select(t => t.Name)
            .ToHashSet(StringComparer.Ordinal);

        var cases = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var type in document.Types.Where(t => t.Kind == TypeKind.Union))
        {
            foreach (var unionCase in type.Cases)
                cases.TryAdd(unionCase, type.Name);
        }

        return new LoweringContext(records, cases);
    }

    // ─── Namespace sanitization ───────────────────────────────────────────────

    private static string SanitizeNamespace(string raw)
    {
        // Keep dots (valid in C# namespace names); replace everything else
        // that is not a letter, digit, underscore, or dot with underscore.
        var sanitized = Regex.Replace(raw.Trim(), @"[^A-Za-z0-9_.]", "_");
        // Ensure each dot-separated segment starts with a letter or underscore.
        var segments = sanitized.Split('.');
        var validSegments = segments
            .Where(s => s.Length > 0)
            .Select(s => char.IsDigit(s[0]) ? "_" + s : s);
        var result = string.Join(".", validSegments);
        return result.Length > 0 ? result : "AISharpGenerated";
    }

    // ─── Type lowering ────────────────────────────────────────────────────────

    /// <summary>
    /// Lowers AI# type declarations to C# type declarations inside
    /// <c>AISharpModule</c>:
    /// <list type="bullet">
    ///   <item>Record types → <c>public sealed record Name(Type field, ...);</c></item>
    ///   <item>Union types → <c>public abstract record Name</c> with one nested
    ///     <c>public sealed record Case() : Name;</c> per case.</item>
    /// </list>
    /// </summary>
    private static void LowerTypes(StringBuilder sb, MirDocument document)
    {
        foreach (var type in document.Types)
        {
            sb.AppendLine();
            sb.AppendLine($"        // AI# type {type.Name}");

            if (type.Kind == TypeKind.Record)
            {
                var fields = string.Join(", ", type.Fields.Select(f =>
                    $"{FieldTypeToCSharp(f.Type)} {f.Name}"));
                sb.AppendLine($"        public sealed record {type.Name}({fields});");
            }
            else
            {
                // Union: abstract base with nested case records. Nesting keeps case names safe
                // when different unions use the same case label.
                sb.AppendLine($"        public abstract record {type.Name}");
                sb.AppendLine("        {");
                foreach (var cas in type.Cases)
                    sb.AppendLine($"            public sealed record {cas}() : {type.Name};");
                sb.AppendLine("        }");
            }
        }

        // PR-37: Lower model-call schemas to C# records so that schema-typed
        // model-call results have a concrete generated target type.
        foreach (var schema in document.Schemas)
        {
            sb.AppendLine();
            sb.AppendLine($"        // AI# schema {schema.Name}");
            var fields = string.Join(", ", schema.Fields.Select(f =>
                $"{FieldTypeToCSharp(f.Type)} {f.Name}"));
            sb.AppendLine($"        public sealed record {schema.Name}({fields});");
        }
    }

    /// <summary>
    /// Type mapping for record fields: same as <see cref="ToCSharpType"/> except
    /// that <c>unit</c> (which maps to <c>void</c>) is mapped to <c>object</c>
    /// since <c>void</c> is not a valid field type in C#.
    /// </summary>
    private static string FieldTypeToCSharp(AISharpType type) =>
        type is PrimitiveAIType { Name: "unit" } ? "object" : ToCSharpType(type);

    // ─── Function lowering ────────────────────────────────────────────────────

    private static void LowerFunction(StringBuilder sb, MirFunction fn, LoweringContext context)
    {
        var returnTypeCSharp = AsyncReturnType(fn.ReturnType, fn.IsAsync);
        var paramList = string.Join(", ", fn.Parameters.Select(p =>
            $"{ToCSharpType(p.Type)} {p.Name}"));
        var asyncMod = fn.IsAsync ? "async " : string.Empty;

        sb.AppendLine();
        sb.AppendLine($"        // AI# fn {fn.Name} (source line {fn.Location.Line})");
        AppendEffectMetadataAttribute(sb, indent: "        ", fn.DeclaredEffects);
        sb.AppendLine($"        public static {asyncMod}{returnTypeCSharp} {fn.Name}({paramList})");
        sb.AppendLine("        {");

        var entryPlans = fn.ContractCheckPlans
            .Where(c => c.Kind == ContractKind.Requires)
            .ToList();
        var exitPlans = fn.ContractCheckPlans
            .Where(c => c.Kind is ContractKind.Ensures or ContractKind.Invariant)
            .ToList();

        LowerEntryGuards(sb, entryPlans);
        LowerEffectGuards(sb, indent: "            ", fn.DeclaredEffects);

        foreach (var stmt in fn.Body)
            LowerStatement(sb, stmt, context, fn.ReturnType, exitPlans);

        sb.AppendLine("        }");
    }

    // ─── Contract lowering ────────────────────────────────────────────────────

    private static void AppendContractRuntimeSupport(StringBuilder sb)
    {
        sb.AppendLine("    public sealed class AISharpContractException : global::System.Exception");
        sb.AppendLine("    {");
        sb.AppendLine("        public AISharpContractException(string contractKind, string expression, int line, int column, int offset)");
        sb.AppendLine("            : base($\"AI# contract '{contractKind}' failed at {line}:{column}: {expression}\")");
        sb.AppendLine("        {");
        sb.AppendLine("            ContractKind = contractKind;");
        sb.AppendLine("            Expression = expression;");
        sb.AppendLine("            Line = line;");
        sb.AppendLine("            Column = column;");
        sb.AppendLine("            Offset = offset;");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        public string ContractKind { get; }");
        sb.AppendLine("        public string Expression { get; }");
        sb.AppendLine("        public int Line { get; }");
        sb.AppendLine("        public int Column { get; }");
        sb.AppendLine("        public int Offset { get; }");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    internal static class AISharpContracts");
        sb.AppendLine("    {");
        sb.AppendLine("        public static void Requires(bool condition, string expression, int line, int column, int offset) =>");
        sb.AppendLine("            Check(condition, \"requires\", expression, line, column, offset);");
        sb.AppendLine();
        sb.AppendLine("        public static void Ensures(bool condition, string expression, int line, int column, int offset) =>");
        sb.AppendLine("            Check(condition, \"ensures\", expression, line, column, offset);");
        sb.AppendLine();
        sb.AppendLine("        public static void Invariant(bool condition, string expression, int line, int column, int offset) =>");
        sb.AppendLine("            Check(condition, \"invariant\", expression, line, column, offset);");
        sb.AppendLine();
        sb.AppendLine("        private static void Check(bool condition, string contractKind, string expression, int line, int column, int offset)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (!condition)");
        sb.AppendLine("                throw new AISharpContractException(contractKind, expression, line, column, offset);");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
    }

    // ─── Effect lowering ──────────────────────────────────────────────────────

    private static readonly IReadOnlyDictionary<string, string> s_effectKindMap =
        new Dictionary<string, string>(StringComparer.Ordinal)
        {
            ["io"]         = "Io",
            ["time"]       = "Time",
            ["random"]     = "Random",
            ["model"]      = "Model",
            ["network"]    = "Network",
            ["net"]        = "Network",
            ["http"]       = "Network",
            ["unsafe_ffi"] = "UnsafeFfi",
            ["unsafe"]     = "UnsafeFfi",
            ["ffi"]        = "UnsafeFfi"
        };

    private static IReadOnlyList<string> BuiltInEffectKindFlags(IReadOnlyList<string> declared)
    {
        if (declared.Count == 0) return Array.Empty<string>();
        var flags = new List<string>(declared.Count);
        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (var name in declared)
        {
            if (s_effectKindMap.TryGetValue(name, out var flag) && seen.Add(flag))
                flags.Add(flag);
        }
        return flags;
    }

    /// <summary>
    /// Emits the <c>[AISharpEffectMetadataAttribute(...)]</c> attribute above a lowered
    /// function/handler so the declared AI# effects are preserved as runtime-visible
    /// metadata. Custom (non-built-in) effect names are kept in the names string and
    /// surface via reflection even when they have no <c>EffectKind</c> flag.
    /// </summary>
    private static void AppendEffectMetadataAttribute(
        StringBuilder sb,
        string indent,
        IReadOnlyList<string> declaredEffects)
    {
        var flags = BuiltInEffectKindFlags(declaredEffects);
        var declared = flags.Count == 0
            ? "AISharpEffectKind.None"
            : string.Join(" | ", flags.Select(f => "AISharpEffectKind." + f));
        var names = EscapeStringLiteral(string.Join(",", declaredEffects));
        sb.AppendLine($"{indent}[AISharpEffectMetadataAttribute({declared}, \"{names}\")]");
    }

    /// <summary>
    /// Emits a runtime <c>AISharpEffects.Require(...)</c> guard for each declared
    /// built-in effect on a function/handler. The guards run before any body statement,
    /// so the ambient effect scope can deny model/network/io/unsafe operations even when
    /// the static effect checker permitted them at a wider scope. Guards are emitted in
    /// declaration order with a stable comment so the generated code cannot silently
    /// escalate effects.
    /// </summary>
    private static void LowerEffectGuards(
        StringBuilder sb,
        string indent,
        IReadOnlyList<string> declaredEffects)
    {
        if (declaredEffects.Count == 0) return;
        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (var name in declaredEffects)
        {
            if (!s_effectKindMap.TryGetValue(name, out var flag)) continue;
            if (!seen.Add(flag)) continue;
            sb.AppendLine($"{indent}// AI# effect guard: {name}");
            sb.AppendLine($"{indent}AISharpEffects.Require(AISharpEffectKind.{flag}, \"{EscapeStringLiteral(name)}\");");
        }
    }

    /// <summary>
    /// Emits an inline runtime-support block that mirrors the
    /// <c>AISharp.Runtime.EffectRuntimeContext</c> surface so the generated assembly is
    /// fully self-contained: lowered code does not need to reference the AI# runtime
    /// package to enforce effect policy. Host code can flip the ambient scope by
    /// calling <c>AISharpEffects.Push(...)</c> from the generated namespace.
    /// </summary>
    private static void AppendEffectRuntimeSupport(StringBuilder sb)
    {
        sb.AppendLine();
        sb.AppendLine("    [global::System.Flags]");
        sb.AppendLine("    public enum AISharpEffectKind");
        sb.AppendLine("    {");
        sb.AppendLine("        None      = 0,");
        sb.AppendLine("        Io        = 1 << 0,");
        sb.AppendLine("        Time      = 1 << 1,");
        sb.AppendLine("        Random    = 1 << 2,");
        sb.AppendLine("        Model     = 1 << 3,");
        sb.AppendLine("        Network   = 1 << 4,");
        sb.AppendLine("        UnsafeFfi = 1 << 5,");
        sb.AppendLine("        All       = Io | Time | Random | Model | Network | UnsafeFfi");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    [global::System.AttributeUsage(global::System.AttributeTargets.Method | global::System.AttributeTargets.Class, Inherited = false)]");
        sb.AppendLine("    public sealed class AISharpEffectMetadataAttribute : global::System.Attribute");
        sb.AppendLine("    {");
        sb.AppendLine("        public AISharpEffectMetadataAttribute(AISharpEffectKind declared, string effectNames)");
        sb.AppendLine("        {");
        sb.AppendLine("            Declared = declared;");
        sb.AppendLine("            EffectNames = effectNames ?? string.Empty;");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        public AISharpEffectKind Declared { get; }");
        sb.AppendLine("        public string EffectNames { get; }");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public sealed class AISharpEffectScopeViolationException : global::System.Exception");
        sb.AppendLine("    {");
        sb.AppendLine("        public AISharpEffectScopeViolationException(string effectName, AISharpEffectKind attempted, AISharpEffectKind allowed)");
        sb.AppendLine("            : base(\"AI# effect violation: attempted '\" + effectName + \"' (\" + attempted + \") but only '\" + allowed + \"' is allowed in this scope.\")");
        sb.AppendLine("        {");
        sb.AppendLine("            EffectName = effectName;");
        sb.AppendLine("            Attempted = attempted;");
        sb.AppendLine("            Allowed = allowed;");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        public string EffectName { get; }");
        sb.AppendLine("        public AISharpEffectKind Attempted { get; }");
        sb.AppendLine("        public AISharpEffectKind Allowed { get; }");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public static class AISharpEffects");
        sb.AppendLine("    {");
        sb.AppendLine("        private static readonly global::System.Threading.AsyncLocal<AISharpEffectKind?> s_current = new global::System.Threading.AsyncLocal<AISharpEffectKind?>();");
        sb.AppendLine();
        sb.AppendLine("        public static AISharpEffectKind Current => s_current.Value ?? AISharpEffectKind.All;");
        sb.AppendLine();
        sb.AppendLine("        public static global::System.IDisposable Push(AISharpEffectKind allowed)");
        sb.AppendLine("        {");
        sb.AppendLine("            var previous = s_current.Value;");
        sb.AppendLine("            s_current.Value = allowed;");
        sb.AppendLine("            return new PopOnDispose(previous);");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        public static void Require(AISharpEffectKind effect, string effectName)");
        sb.AppendLine("        {");
        sb.AppendLine("            var allowed = Current;");
        sb.AppendLine("            if ((allowed & effect) != effect)");
        sb.AppendLine("                throw new AISharpEffectScopeViolationException(effectName, effect, allowed);");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        private sealed class PopOnDispose : global::System.IDisposable");
        sb.AppendLine("        {");
        sb.AppendLine("            private readonly AISharpEffectKind? _previous;");
        sb.AppendLine("            private int _disposed;");
        sb.AppendLine("            public PopOnDispose(AISharpEffectKind? previous) { _previous = previous; }");
        sb.AppendLine("            public void Dispose()");
        sb.AppendLine("            {");
        sb.AppendLine("                if (global::System.Threading.Interlocked.Exchange(ref _disposed, 1) == 0)");
        sb.AppendLine("                    s_current.Value = _previous;");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
    }

    /// <summary>
    /// Emits entry-point guards for <c>requires</c> contract clauses.
    /// Each guard calls the generated runtime helper when the expression evaluates to
    /// <c>false</c>, preserving the AI# source location on the thrown exception.
    /// </summary>
    private static void LowerEntryGuards(
        StringBuilder sb,
        IReadOnlyList<MirContractCheckPlan> plans)
    {
        foreach (var plan in plans)
        {
            sb.AppendLine($"            // AI# {ContractHook(plan.Kind)}: {plan.Expression}");
            EmitContractCheckCall(sb, plan, plan.Expression);
        }
    }

    private static string EscapeStringLiteral(string s) =>
        s.Replace("\\", "\\\\").Replace("\"", "\\\"");

    private static void EmitContractCheckCall(StringBuilder sb, MirContractCheckPlan plan, string conditionExpression)
    {
        if (plan.CheckMode == MirContractCheckMode.VerificationOnly)
        {
            sb.AppendLine($"            // AI# {ContractHook(plan.Kind)} verification-only check omitted at runtime.");
            return;
        }

        if (plan.CheckMode == MirContractCheckMode.Debug)
            sb.AppendLine("#if DEBUG");

        sb.AppendLine($"            AISharpContracts.{ContractHelper(plan.Kind)}({conditionExpression}, " +
                      $"\"{EscapeStringLiteral(plan.Expression)}\", {plan.Location.Line}, {plan.Location.Column}, {plan.Location.Offset});");

        if (plan.CheckMode == MirContractCheckMode.Debug)
            sb.AppendLine("#endif");
    }

    private static string ContractHook(ContractKind kind) =>
        kind switch
        {
            ContractKind.Requires => "requires",
            ContractKind.Ensures => "ensures",
            ContractKind.Invariant => "invariant",
            _ => "contract"
        };

    private static string ContractHelper(ContractKind kind) =>
        kind switch
        {
            ContractKind.Requires => "Requires",
            ContractKind.Ensures => "Ensures",
            ContractKind.Invariant => "Invariant",
            _ => "Requires"
        };

    // ─── Statement lowering ───────────────────────────────────────────────────

    private static void LowerStatement(
        StringBuilder sb,
        MirStatement stmt,
        LoweringContext context,
        AISharpType? expectedReturnType = null,
        IReadOnlyList<MirContractCheckPlan>? exitPlans = null)
    {
        switch (stmt)
        {
            case MirLetStatement let:
                sb.AppendLine($"            // AI# let {let.Name} (source line {let.Location.Line})");
                sb.AppendLine($"            var {let.Name} = {LowerExpression(let.Initializer, context, let.AnnotationType)};");
                break;

            case MirReturnStatement ret:
                sb.AppendLine($"            // AI# return (source line {ret.Location.Line})");
                if (expectedReturnType is PrimitiveAIType { Name: "unit" })
                {
                    LowerExitContractGuards(sb, exitPlans, resultExpr: null);
                    sb.AppendLine("            return;");
                }
                else if (exitPlans is { Count: > 0 })
                {
                    // Capture the return value so exit contracts can reference `result`.
                    var retExpr = LowerExpression(ret.Expression, context, expectedReturnType);
                    sb.AppendLine($"            var __result = {retExpr};");
                    LowerExitContractGuards(sb, exitPlans, resultExpr: "__result");
                    sb.AppendLine("            return __result;");
                }
                else
                {
                    sb.AppendLine($"            return {LowerExpression(ret.Expression, context, expectedReturnType)};");
                }
                break;

            case MirExpressionStatement expr:
                sb.AppendLine($"            {LowerExpression(expr.Expression, context)};");
                break;

            case MirTaskGroupStatement tg:
                sb.AppendLine($"            // task group {tg.Name ?? "(unnamed)"}");
                foreach (var s in tg.Statements) LowerStatement(sb, s, context, expectedReturnType, exitPlans);
                break;

            case MirUsingStatement us:
                sb.AppendLine($"            // using {us.ResourceName}");
                foreach (var s in us.Statements) LowerStatement(sb, s, context, expectedReturnType, exitPlans);
                break;

            case MirSpawnStatement spawn:
                sb.AppendLine($"            var {spawn.Name} = {LowerExpression(spawn.Expression, context)};");
                break;

            case MirAllStatement all:
                sb.AppendLine($"            await Task.WhenAll({string.Join(", ", all.Targets)});");
                break;

            case MirMatchStatement ms:
                LowerMatchStatement(sb, ms, context);
                break;

            default:
                sb.AppendLine($"            // (unhandled statement kind {stmt.GetType().Name})");
                break;
        }
    }

    /// <summary>
    /// Emits <c>ensures</c> and <c>invariant</c> guards immediately before a return point.
    /// When <paramref name="resultExpr"/> is non-null, occurrences of the word
    /// <c>result</c> in the contract expression are replaced with it.
    /// </summary>
    private static void LowerExitContractGuards(
        StringBuilder sb,
        IReadOnlyList<MirContractCheckPlan>? plans,
        string? resultExpr)
    {
        if (plans is not { Count: > 0 })
            return;

        foreach (var plan in plans)
        {
            var expr = resultExpr is not null
                ? Regex.Replace(plan.Expression, @"\bresult\b", resultExpr)
                : plan.Expression;
            sb.AppendLine($"            // AI# {ContractHook(plan.Kind)}: {plan.Expression}");
            EmitContractCheckCall(sb, plan, expr);
        }
    }

    // ─── Match statement lowering ─────────────────────────────────────────────

    /// <summary>
    /// Lowers an AI# <c>match</c> statement to a C# switch expression captured
    /// via a discard (<c>_ = scrutinee switch { ... };</c>).
    /// <list type="bullet">
    ///   <item>Named union-case patterns become <c>UnionType.CaseName</c> type patterns.</item>
    ///   <item>Wildcard <c>_</c> maps directly to C# <c>_</c>.</item>
    ///   <item>When no wildcard arm is present, a <c>_ => default</c> fallback is appended
    ///         so the generated switch expression is always exhaustive.</item>
    /// </list>
    /// </summary>
    private static void LowerMatchStatement(
        StringBuilder sb,
        MirMatchStatement ms,
        LoweringContext context)
    {
        sb.AppendLine($"            // match {ms.Scrutinee} (source line {ms.Location.Line})");
        sb.AppendLine($"            _ = {ms.Scrutinee} switch");
        sb.AppendLine("            {");

        var hasWildcard = ms.Arms.Any(a => a.Pattern == "_");

        foreach (var arm in ms.Arms)
        {
            string csharpPattern;
            if (arm.Pattern == "_")
            {
                csharpPattern = "_";
            }
            else if (context.UnionCaseOwners.TryGetValue(arm.Pattern, out var ownerType))
            {
                csharpPattern = $"{ownerType}.{arm.Pattern}";
            }
            else
            {
                csharpPattern = arm.Pattern;
            }

            var armBody = LowerExpression(arm.Body, context);
            sb.AppendLine($"                {csharpPattern} => {armBody},");
        }

        if (!hasWildcard)
            sb.AppendLine("                _ => default,");

        sb.AppendLine("            };");
    }

    private static string LowerExpression(
        MirExpression expression,
        LoweringContext context,
        AISharpType? expectedType = null) =>
        LowerExpressionText(expression.Text, context, expectedType ?? expression.Type);

    private static string LowerExpressionText(
        string expressionText,
        LoweringContext context,
        AISharpType? expectedType)
    {
        var trimmed = expressionText.Trim();

        if (string.Equals(trimmed, "unit", StringComparison.Ordinal))
            return "default";

        // PR-37: Lower fluent model-call expressions (`model PROVIDER "ID" ... .run()`)
        // to a deterministic typed default so the surrounding C# remains compilable
        // even though the AI runtime model dispatcher is not yet wired into lowering.
        // The schema-constrained return type is preserved via the C# target type.
        if (IsModelCallExpression(trimmed))
        {
            var targetType = expectedType is not null
                ? FieldTypeToCSharp(expectedType)
                : "object";
            return $"default({targetType})!";
        }

        if (TryGetExpectedUnionName(expectedType, out var expectedUnion)
            && context.UnionCaseOwners.TryGetValue(trimmed, out var owner)
            && string.Equals(owner, expectedUnion, StringComparison.Ordinal))
        {
            return $"new {owner}.{trimmed}()";
        }

        var callMatch = Regex.Match(
            trimmed,
            @"^(?<name>[A-Za-z_][A-Za-z0-9_]*)\((?<args>.*)\)$",
            RegexOptions.CultureInvariant);
        if (!callMatch.Success)
            return trimmed;

        var name = callMatch.Groups["name"].Value;
        var args = callMatch.Groups["args"].Value.Trim();
        if (context.RecordTypes.Contains(name))
            return $"new {name}({args})";

        if (TryGetExpectedUnionName(expectedType, out expectedUnion)
            && context.UnionCaseOwners.TryGetValue(name, out owner)
            && string.Equals(owner, expectedUnion, StringComparison.Ordinal)
            && args.Length == 0)
        {
            return $"new {owner}.{name}()";
        }

        return trimmed;
    }

    private static readonly Regex s_modelCallRegex = new(
        @"^model\s+[A-Za-z_][A-Za-z0-9_#]*\s+""[^""]*"".*\.run\s*\(\s*\)\s*$",
        RegexOptions.CultureInvariant | RegexOptions.Singleline);

    private static bool IsModelCallExpression(string trimmed) =>
        s_modelCallRegex.IsMatch(trimmed);

    private static bool TryGetExpectedUnionName(AISharpType? type, out string name)
    {
        switch (type)
        {
            case UnionAIType { Name: { Length: > 0 } unionName }:
                name = unionName;
                return true;
            case NamedAIType { Name: { Length: > 0 } named }:
                name = named;
                return true;
            default:
                name = string.Empty;
                return false;
        }
    }

    // ─── Actor lowering ───────────────────────────────────────────────────────

    /// <summary>
    /// Lowers a <see cref="MirActor"/> to a C# class outside <c>AISharpModule</c>:
    /// <list type="bullet">
    ///   <item>Each state member becomes a <c>private</c> field initialised to <c>default</c>.</item>
    ///   <item>Each handler becomes a <c>public async Task&lt;T&gt;</c> instance method.</item>
    /// </list>
    /// </summary>
    private static void LowerActor(StringBuilder sb, MirActor actor, LoweringContext context)
    {
        sb.AppendLine();
        sb.AppendLine($"    // AI# actor {actor.Name} (source line {actor.Location.Line})");
        sb.AppendLine($"    public sealed class {actor.Name}");
        sb.AppendLine("    {");

        foreach (var state in actor.StateMembers)
        {
            var fieldType = ToCSharpType(state.Type);
            sb.AppendLine($"        private {fieldType} {state.Name} = default({fieldType})!;");
        }

        foreach (var handler in actor.Handlers)
            LowerActorHandler(sb, handler, context);

        sb.AppendLine("    }");
    }

    /// <summary>
    /// Lowers an actor handler as a <c>public async Task&lt;T&gt;</c> instance method.
    /// </summary>
    private static void LowerActorHandler(StringBuilder sb, MirFunction fn, LoweringContext context)
    {
        var returnTypeCSharp = AsyncReturnType(fn.ReturnType, isAsync: true);
        var paramList = string.Join(", ", fn.Parameters.Select(p =>
            $"{ToCSharpType(p.Type)} {p.Name}"));

        sb.AppendLine();
        sb.AppendLine($"        // AI# handler {fn.Name} (source line {fn.Location.Line})");
        AppendEffectMetadataAttribute(sb, indent: "        ", fn.DeclaredEffects);
        sb.AppendLine($"        public async {returnTypeCSharp} {fn.Name}({paramList})");
        sb.AppendLine("        {");

        var entryPlans = fn.ContractCheckPlans
            .Where(c => c.Kind == ContractKind.Requires)
            .ToList();
        var exitPlans = fn.ContractCheckPlans
            .Where(c => c.Kind is ContractKind.Ensures or ContractKind.Invariant)
            .ToList();

        LowerEntryGuards(sb, entryPlans);
        LowerEffectGuards(sb, indent: "            ", fn.DeclaredEffects);

        foreach (var stmt in fn.Body)
            LowerStatement(sb, stmt, context, fn.ReturnType, exitPlans);

        sb.AppendLine("        }");
    }

    /// <summary>
    /// Returns the C# return type for a function, wrapping in <c>Task&lt;T&gt;</c> or
    /// <c>Task</c> when the function is async.
    /// </summary>
    private static string AsyncReturnType(AISharpType returnType, bool isAsync)
    {
        if (!isAsync)
            return ToCSharpType(returnType);
        return returnType is PrimitiveAIType { Name: "unit" }
            ? "Task"
            : $"Task<{ToCSharpType(returnType)}>";
    }

    // ─── Type mapping ─────────────────────────────────────────────────────────

    private static string ToCSharpType(AISharpType type) => type switch
    {
        PrimitiveAIType p => p.Name switch
        {
            "string"  => "string",
            "int"     => "int",
            "float"   => "double",
            "bool"    => "bool",
            "unit"    => "void",
            _         => p.Name
        },
        NamedAIType n     => n.Name,
        GenericAIType g   => $"{g.Head}<{string.Join(", ", g.Args.Select(ToCSharpType))}>",
        ResultAIType r    => $"AISharpResult<{ToCSharpType(r.OkType)}, {ToCSharpType(r.ErrorType)}>",
        OptionAIType o    => $"{ToCSharpType(o.ValueType)}?",
        ResourceAIType rs => rs.Name,
        _                 => "object"
    };
